/**
 * Calculate user cultivation realm level and progress
 * @param {number} meritPoints
 * @returns {{ level: number, title: string, minMerit: number, nextMerit: number|null, progress: number, auraColor: string, description: string }}
 */
export function getRealmInfo(meritPoints = 0) {
  const points = Math.max(0, Number(meritPoints) || 0);

  for (let i = REALM_LEVELS.length - 1; i >= 0; i--) {
    const current = REALM_LEVELS[i];
    if (points >= current.minMerit) {
      const next = REALM_LEVELS[i + 1] || null;
      if (!next) {
        return {
          level: current.level,
          title: current.title,
          minMerit: current.minMerit,
          nextMerit: null,
          progress: 1.0,
          auraColor: current.auraColor,
          description: current.description
        };
      }
      const range = next.minMerit - current.minMerit;
      const progress = Math.min(1, Math.max(0, (points - current.minMerit) / range));
      return {
        level: current.level,
        title: current.title,
        minMerit: current.minMerit,
        nextMerit: next.minMerit,
        progress: Number(progress.toFixed(4)),
        auraColor: current.auraColor,
        description: current.description
      };
    }
  }

  const first = REALM_LEVELS[0];
  return {
    level: first.level,
    title: first.title,
    minMerit: first.minMerit,
    nextMerit: REALM_LEVELS[1].minMerit,
    progress: 0,
    auraColor: first.auraColor,
    description: first.description
  };
}

